"""Generate crates/terrio-crs/data/grids.tsv, the grids PROJ's database knows and where to get them.

For each grid of proj.db's ``grid_alternatives`` table: the name PROJ uses for it (its name on the
PROJ CDN, or the original name of a grid PROJ does not distribute), its names before PROJ 7
(``old_proj_grid_name``, which PROJ also opens the grid by), the producer's names
(``original_grid_name``: file names, but also companion files, web pages and URLs, which PROJ
only reports the grid by), the URL to download it from, and whether that URL gives the file
itself and the grid has an open licence. These are what PROJ's
``proj_coordoperation_get_grid_used`` reports for a grid (``url``, ``direct_download``,
``open_license``).

Lines: ``name<TAB>old names<TAB>producer's names<TAB>url<TAB>direct_download<TAB>open_license``
(names comma-separated), after a ``#`` header; ``url`` is empty when it is
``https://cdn.proj.org/`` followed by the name.

Usage: python scripts/gen_grid_catalog.py

Needs pyproj on the PROJ version ``epsg.tsv.zst`` was generated from.
"""

import os
import sqlite3

import pyproj

OUT = os.path.join(
    os.path.dirname(__file__), "..", "crates", "terrio-crs", "data", "grids.tsv"
)
CDN = "https://cdn.proj.org/"


def main():
    """Write the table."""
    db = sqlite3.connect(os.path.join(pyproj.datadir.get_data_dir(), "proj.db"))
    query = """
        SELECT original_grid_name, proj_grid_name, old_proj_grid_name, url, direct_download, open_license
        FROM grid_alternatives
    """
    grids = {}
    for original, proj, old, url, direct, open_license in db.execute(query):
        name = proj or original
        entry = grids.setdefault(name, {"old": set(), "original": set(), "info": set()})
        if old and old != name:
            entry["old"].add(old)
        # proj.db marks a grid it has no transformation for yet by a placeholder, not a name.
        placeholder = (original or "").startswith("NOT-YET-IN-GRID-TRANSFORMATION-")
        if original and original != name and original != old and not placeholder:
            entry["original"].add(original)
        if not url:
            raise SystemExit(f"{name}: no URL in proj.db")
        entry["info"].add((url, int(bool(direct)), int(bool(open_license))))
    rows = []
    for name in sorted(grids):
        info = grids[name]["info"]
        if len(info) != 1:
            raise SystemExit(f"{name}: several download records {sorted(info)}")
        url, direct, open_license = info.pop()
        if url == CDN + name:
            url = ""
        entry = grids[name]
        old, original = (
            ",".join(sorted(entry["old"])),
            ",".join(sorted(entry["original"])),
        )
        rows.append((name, old, original, url, direct, open_license))
    header = f"# Grids of PROJ's database, via PROJ {pyproj.proj_version_str}. Generated by scripts/gen_grid_catalog.py.\n"
    db.close()
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(header + "".join("\t".join(map(str, r)) + "\n" for r in rows))
    print(f"{len(rows)} grids")


if __name__ == "__main__":
    main()
