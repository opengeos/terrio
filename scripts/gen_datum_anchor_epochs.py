"""Generate crates/terrio-crs/data/datum_anchor_epochs.tsv: the anchor epochs of EPSG datums.

The geodetic and vertical datums of PROJ's database with an anchor epoch (`anchor_epoch`), which
PROJ writes in their PROJJSON (`datum.anchor_epoch`) and WKT 2 (`ANCHOREPOCH`): one
`code<TAB>epoch` line each, by code (opengeos/terrio#1012, item 65).

Usage: python scripts/gen_datum_anchor_epochs.py (needs pyproj)
"""

import sqlite3
from pathlib import Path

import pyproj

OUT = (
    Path(__file__).resolve().parents[1]
    / "crates/terrio-crs/data/datum_anchor_epochs.tsv"
)


def main():
    db = sqlite3.connect(Path(pyproj.datadir.get_data_dir()) / "proj.db")
    rows = db.execute(
        "SELECT code, anchor_epoch FROM geodetic_datum WHERE auth_name = 'EPSG' AND anchor_epoch IS NOT NULL "
        "UNION SELECT code, anchor_epoch FROM vertical_datum WHERE auth_name = 'EPSG' AND anchor_epoch IS NOT NULL"
    ).fetchall()
    lines = sorted((int(code), float(epoch)) for code, epoch in rows)
    header = f"# EPSG datums' anchor epochs, via PROJ {pyproj.proj_version_str}. Generated by scripts/gen_datum_anchor_epochs.py.\n"
    OUT.write_text(header + "".join(f"{code}\t{epoch!r}\n" for code, epoch in lines))
    print(f"{len(lines)} datums")


if __name__ == "__main__":
    main()
