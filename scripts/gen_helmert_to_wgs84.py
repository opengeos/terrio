"""Generate the datum shifts to WGS 84 that ``terrio_crs::helmert_to_wgs84`` is checked against.

For every EPSG geographic 2D CRS, deprecated ones too, the first of pyproj's
``TransformerGroup("EPSG:<code>", "EPSG:4326").transformers`` that needs no grid, read from the
PROJ pipeline it runs: when its only datum shift is one Helmert step of 3 or 7 parameters (without
``exact`` rotations, a pivot point or rates of change), its parameters as ``+towgs84`` carries them
(metres, arc-seconds in the position vector convention, ppm; all negated for an ``inv`` step), and
zeros when it shifts nothing. Conversions around the step (a prime meridian, geographic to
geocentric) do not count, so this includes a concatenation PROJ runs as one Helmert step. PROJ's
ballpark is no transformation; when it comes first, the transformation is the one PROJ's
``crs_to_crs`` picks through another datum when the direct ones need grids (pyproj's
``Transformer.from_crs``), if any.

Writes ``crates/terrio-crs/tests/data/helmert_to_wgs84.tsv``, lines ``code<TAB>parameters``, the
seven parameters comma-separated, or ``- `` and why there are none.

Usage: python scripts/gen_helmert_to_wgs84.py

Needs pyproj on PROJ 9.9.0 (conda-forge ``pyproj=3.8.0 proj=9.9.0``) with no grids installed; the
network is turned off.
"""

import os
import tempfile
from pathlib import Path

import pyproj
import pyproj.network
from pyproj.database import get_codes
from pyproj.transformer import Transformer, TransformerGroup

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "crates" / "terrio-crs" / "tests" / "data" / "helmert_to_wgs84.tsv"

# The pipeline steps that convert coordinates without a datum shift.
CONVERSIONS = {"axisswap", "unitconvert", "push", "pop", "cart", "longlat", "noop"}


def steps(definition):
    """A pipeline's steps: whether inverted, the operation, and its parameters."""
    out = []
    for step in definition.split(" step ")[1:] if definition.startswith("proj=pipeline") else [definition]:
        words = step.split()
        inv = words[0] == "inv"
        params = dict(w.split("=", 1) if "=" in w else (w, "") for w in words[inv:])
        out.append((inv, params.pop("proj"), params))
    return out


def helmert(definition):
    """The seven parameters of a pipeline's one Helmert step, zeros without shift, or why not."""
    shifts = [s for s in steps(definition) if s[1] not in CONVERSIONS]
    if not shifts:
        return [0.0] * 7
    if len(shifts) > 1:
        return "- " + " + ".join(s[1] for s in shifts)
    inv, name, p = shifts[0]
    if name != "helmert":
        return f"- {name}"
    if set(p) - {"x", "y", "z", "rx", "ry", "rz", "s", "convention"}:
        return "- helmert " + " ".join(sorted(set(p) - {"x", "y", "z", "rx", "ry", "rz", "s", "convention"}))
    v = [float(p.get(k, 0)) for k in ("x", "y", "z", "rx", "ry", "rz", "s")]
    if p.get("convention") == "coordinate_frame":
        v[3:6] = [-r for r in v[3:6]]
    return [-x for x in v] if inv else v


def first(code):
    """What the first operation without grids gives."""
    for t in TransformerGroup(f"EPSG:{code}", "EPSG:4326").transformers:
        if "grids=" in t.definition:
            continue
        if "Ballpark" in t.description:
            # Without the grids of the direct transformations, PROJ's crs_to_crs (GDAL's and
            # terrio's transformation) searches through other datums first (RD/83 through ETRS89).
            other = Transformer.from_crs(f"EPSG:{code}", "EPSG:4326")
            if "Ballpark" in other.description or "grids=" in other.definition or other.description == t.description:
                return "- ballpark"
            return helmert(other.definition)
        return helmert(t.definition)
    return "- none"


def text(v):
    """A parameter as the shortest decimal that reads back, without a trailing ``.0``."""
    v = 0.0 if v == 0 else v
    s = repr(v)
    return s[:-2] if s.endswith(".0") else s


def main():
    assert pyproj.proj_version_str == "9.9.0", pyproj.proj_version_str
    pyproj.network.set_network_enabled(False)
    codes = sorted(int(c) for c in get_codes("EPSG", "GEOGRAPHIC_2D_CRS", allow_deprecated=True))
    lines = []
    for code in codes:
        if code == 4326:
            continue
        r = first(code)
        lines.append(f"{code}\t{r if isinstance(r, str) else ','.join(text(v) for v in r)}")
    text_out = (
        "# The datum shift to WGS 84 of EPSG geographic 2D CRSs: PROJ 9.9.0's first transformation without grids.\n"
        "# Generated by scripts/gen_helmert_to_wgs84.py.\n" + "\n".join(lines) + "\n"
    )
    # A temporary file of this run's own, beside the fixture, replacing it once written.
    fd, tmp = tempfile.mkstemp(dir=OUT.parent, prefix=OUT.name, suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text_out)
        os.replace(tmp, OUT)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise
    print(f"{len(lines)} CRSs, {sum(not line.split(chr(9))[1].startswith('- ') for line in lines)} with a Helmert shift (zeros for none)")


if __name__ == "__main__":
    main()
