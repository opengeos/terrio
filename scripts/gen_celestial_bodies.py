"""Generate crates/terrio-crs/src/bodies.rs from PROJ 9.8.1's ``celestial_body`` table (see NOTICE).

The table names the bodies of the IAU_2015 CRSs by NAIF code, and gives the semi-major axis by
which PROJ names the body of another ellipsoid (``Ellipsoid::guessBodyName``).

Usage: python scripts/gen_celestial_bodies.py (needs pyproj 3.8.0)
"""

import os
import sqlite3
from pathlib import Path

import pyproj

OUT = Path(__file__).resolve().parents[1] / "crates/terrio-crs/src/bodies.rs"


def main():
    assert pyproj.proj_version_str == "9.8.1", pyproj.proj_version_str
    db = sqlite3.connect(os.path.join(pyproj.datadir.get_data_dir(), "proj.db"))
    naif = db.execute(
        "SELECT CAST(code AS INTEGER), name FROM celestial_body WHERE auth_name = 'IAU_2015' ORDER BY CAST(code AS INTEGER)"
    ).fetchall()
    radii = db.execute(
        "SELECT DISTINCT name, semi_major_axis FROM celestial_body ORDER BY semi_major_axis, name"
    ).fetchall()
    # REUSE-IgnoreStart (the generated file's tags, not this script's)
    lines = [
        "// SPDX-FileCopyrightText: PROJ contributors",
        "// SPDX-FileCopyrightText: Copyright (c) 2021, Hobu Inc",
        "// SPDX-FileCopyrightText: Copyright © 2010-2025 Esri",
        "// SPDX-FileCopyrightText: Copyright (c) 2026 Qiusheng Wu and Terrio contributors",
        "// SPDX-License-Identifier: MIT AND Apache-2.0",
        "//",
        "// Generated by scripts/gen_celestial_bodies.py from PROJ 9.8.1's celestial_body table (IAU_2015",
        "// bodies from data/sql/iau.sql, ESRI bodies from Esri's projection engine documentation; see",
        "// NOTICE). Do not edit.",
        # REUSE-IgnoreEnd
        "",
        "/// The names of the IAU_2015 bodies, by NAIF code.",
        f"pub(crate) const NAIF: [(u32, &str); {len(naif)}] = [",
    ]
    lines += [f'    ({code}, "{name}"),' for code, name in naif]
    lines += [
        "];",
        "",
        "/// The bodies of every authority and their semi-major axes in metres, by axis.",
        f"pub(crate) const RADII: [(&str, f64); {len(radii)}] = [",
    ]
    lines += [f'    ("{name}", {float(a)!r}),' for name, a in radii]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(naif)} NAIF codes and {len(radii)} radii written to {OUT}")


if __name__ == "__main__":
    main()
