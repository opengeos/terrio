epsg_cases = [32613, 3413, 5070, 3035, 2056, 2263, 27700, 3031]

rng = np.random.default_rng(7)


def points(crs):
    """Random WGS 84 points around a CRS's origin.

    Args:
        crs: The CRS.

    Returns:
        tuple: Longitudes and latitudes.
    """
    d = crs.to_dict() if crs.to_dict() else {}
    lon0 = float(d.get("lon_0", d.get("lonc", 0.0)))
    lat0 = float(d.get("lat_0", 0.0))
    if abs(lat0) >= 80:
        lat0 = float(d.get("lat_ts", lat0)) if abs(float(d.get("lat_ts", 90))) < 89 else lat0 * 0.85
    lon = lon0 + rng.uniform(-5, 5, 6)
    lat = np.clip(lat0 + rng.uniform(-5, 5, 6), -84, 84)
    return lon, lat


def strip_id(w):
    """A WKT without its root's ID (its last node).

    Args:
        w: The WKT.

    Returns:
        str: The WKT without it.
    """
    m = re.search(r',ID\["EPSG",\d+\]\]$', w)
    assert m, w[-80:]
    return w[: m.start()] + "]"


def rs(s):
    """A Rust string literal.

    Args:
        s: The string.

    Returns:
        str: The literal.
    """
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = ["// Generated by scripts/gen_wkt2_cases.py, with pyproj " + pyproj.__version__ + " (PROJ " + pyproj.proj_version_str + "): WKT 2 of PROJ strings and of",
       "// EPSG CRSs without their root ID, with reference coordinates of WGS 84 points.",
       "",
       "pub struct Case {",
       "    pub name: &'static str,",
       "    /// The CRS terrio reads the WKT against: a PROJ string or an EPSG code.",
       "    pub reference: &'static str,",
       "    pub wkt1: Option<&'static str>,",
       "    pub wkt2_2019: &'static str,",
       "    pub wkt2_2015: &'static str,",
       "    /// WGS 84 longitudes and latitudes, and PROJ's coordinates of them (`None` when PROJ",
       "    /// shifts the datum by a grid terrio may not have).",
       "    pub points: &'static [(f64, f64)],",
       "    pub proj: Option<&'static [(f64, f64)]>,",
       "}",
       "",
       "pub const CASES: &[Case] = &["]
for name, p in list(proj_cases.items()) + [(f"epsg_{c}", f"EPSG:{c}") for c in epsg_cases]:
    crs = pyproj.CRS(p)
    if name.startswith("epsg_"):
        w19 = strip_id(crs.to_wkt(V.WKT2_2019, pretty=False))
        w15 = strip_id(crs.to_wkt(V.WKT2_2015, pretty=False))
    else:
        w19 = crs.to_wkt(V.WKT2_2019, pretty=False)
        w15 = crs.to_wkt(V.WKT2_2015, pretty=False)
    try:
        w1 = crs.to_wkt(V.WKT1_GDAL, pretty=False)
    except Exception:
        w1 = None
    lon, lat = points(crs)
    tr = pyproj.Transformer.from_crs("EPSG:4326", crs, always_xy=True)
    x, y = tr.transform(lon, lat)
    shifts = "NAD27" in p or name in ("epsg_27700",)
    pts = ", ".join(f"({float(a)!r}, {float(b)!r})" for a, b in zip(lon, lat))
    ref = ", ".join(f"({float(a)!r}, {float(b)!r})" for a, b in zip(x, y))
    out += ["    Case {",
            f"        name: {rs(name)},",
            f"        reference: {rs(p)},",
            f"        wkt1: {('Some(' + rs(w1) + ')') if w1 else 'None'},",
            f"        wkt2_2019: {rs(w19)},",
            f"        wkt2_2015: {rs(w15)},",
            f"        points: &[{pts}],",
            f"        proj: {'None' if shifts else 'Some(&[' + ref + '])'},",
            "    },"]
out.append("];")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
