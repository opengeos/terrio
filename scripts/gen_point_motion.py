"""Generate crates/terrio/data/point_motion.tsv, the point motion operations of EPSG datums.

A point motion operation moves coordinates of a CRS from one coordinate epoch to another with a
velocity model, such as the Canada velocity grid of NAD83(CSRS). For each datum the EPSG dataset
has one for, the table gives the geodetic steps PROJ runs between two epochs of its CRSs (from
``projinfo -s EPSG:code@2010 -t EPSG:code@2020``), with ``dt={dt}`` in place of the time span:
terrio fills it in with the target epoch minus the source epoch.

Lines: ``datum<TAB>name<TAB>steps``, after a ``#`` header.

Usage: python scripts/gen_point_motion.py

Needs pyproj and ``projinfo``, with the PROJ version of ``epsg.tsv.zst``.
"""

import os
import re
import sqlite3
import subprocess
import sys

import pyproj

sys.path.insert(0, os.path.dirname(__file__))
import gen_epsg_table as epsg  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "crates", "terrio", "data", "point_motion.tsv")


def main():
    """Write the table."""
    db = sqlite3.connect(os.path.join(pyproj.datadir.get_data_dir(), "proj.db"))
    query = """
        SELECT t.name, g.code, g.datum_code FROM grid_transformation t
        JOIN geodetic_crs g ON g.auth_name = t.source_crs_auth_name AND g.code = t.source_crs_code
        WHERE t.method_name LIKE 'Point motion%' AND t.deprecated = 0 AND t.auth_name = 'EPSG'
        ORDER BY g.datum_code, t.code DESC
    """
    rows, seen = [], set()
    for name, code, datum in db.execute(query):
        if datum in seen:
            continue
        args = ["projinfo", "-s", f"EPSG:{code}@2010", "-t", f"EPSG:{code}@2020", "--spatial-test", "intersects"]
        args += ["--grid-check", "known_available", "-o", "PROJ", "--single-line"]
        text = subprocess.run(args, capture_output=True, text=True, env=dict(os.environ, PROJ_NETWORK="ON")).stdout
        proj = next((line for line in text.splitlines() if line.startswith("+proj=") and "deformation" in line), None)
        if proj is None:
            continue
        steps = epsg.datum_steps(proj.replace("+", ""))
        if not steps or "deformation" not in steps:
            continue
        seen.add(datum)
        rows.append((datum, name, re.sub(r"\bdt=10\b", "dt={dt}", steps)))
    header = f"# Point motion operations of EPSG datums, via PROJ {pyproj.proj_version_str}. Generated by scripts/gen_point_motion.py.\n"
    with open(OUT, "w") as f:
        f.write(header + "".join("\t".join(map(str, r)) + "\n" for r in rows))
    print(f"{len(rows)} datums")


if __name__ == "__main__":
    main()
