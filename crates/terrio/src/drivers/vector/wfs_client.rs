const METADATA_CAP: u64 = 16 << 20;
const PAGE_CAP: u64 = 64 << 20;
const XML_ELEMENTS: usize = 1_000_000;
// Element nodes, decoded strings, coordinate parsing and temporary vectors.
const XML_WORKSPACE_FACTOR: usize = 64;

/// A service summary; unknown counts stay null rather than being reported as zero.
#[derive(Debug, Clone, Serialize)]
pub struct ServiceInfo {
    /// The driver name, WFS.
    pub driver: String,
    /// The negotiated WFS version.
    pub version: String,
    /// True: this summary does not fetch features.
    pub metadata_only: bool,
    /// Advertised feature types.
    pub layers: Vec<ServiceLayerInfo>,
}

/// One advertised feature type, without fetching its features.
#[derive(Debug, Clone, Serialize)]
pub struct ServiceLayerInfo {
    /// The advertised, namespace-qualified feature type name.
    pub name: String,
    /// The human-readable title, when advertised.
    pub title: Option<String>,
    /// Unknown until the schema or features are read.
    pub geometry_type: String,
    /// Unknown in capabilities-only summaries.
    pub feature_count: Option<usize>,
    /// The default CRS, when recognized.
    pub crs: CrsSummary,
    /// Unknown without reading features.
    pub extent: Option<[f64; 4]>,
    /// The advertised WGS 84 bounds, when present.
    pub wgs84_extent: Option<[f64; 4]>,
    /// Empty until DescribeFeatureType is requested.
    pub fields: Vec<crate::info::FieldInfo>,
}

impl ServiceInfo {
    pub(crate) fn to_text(&self) -> String {
        let mut out = format!("Driver: WFS\nWFS version: {}\nLayers: {}\n", self.version, self.layers.len());
        for layer in &self.layers {
            let _ = writeln!(out, "\nLayer: {}", layer.name);
            if let Some(title) = &layer.title {
                let _ = writeln!(out, "Title: {title}");
            }
            let _ = writeln!(out, "Features: unknown (service metadata)");
            let _ = writeln!(out, "CRS: {}", layer.crs.line());
        }
        out
    }
}

fn invalid(message: impl std::fmt::Display) -> Error {
    Error::InvalidData(format!("WFS: {message}"))
}
fn limited(message: impl std::fmt::Display) -> Error {
    Error::ResourceLimit(format!("WFS: {message}"))
}

