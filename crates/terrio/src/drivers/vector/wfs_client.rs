fn safe_url(url: &str) -> &str {
    url.split(['?', '#']).next().unwrap_or(url)
}

/// A KVP value generated by this client; original vendor/auth parameters retain their raw encoding.
fn encode(value: &str) -> String {
    let mut out = String::new();
    for byte in value.bytes() {
        if byte.is_ascii_alphanumeric() || b"-._~".contains(&byte) {
            out.push(byte as char);
        } else {
            let _ = write!(out, "%{byte:02X}");
        }
    }
    out
}

fn request_url(base: &str, values: &[(&str, String)]) -> String {
    let base = base.split('#').next().unwrap_or(base);
    let (base, query) = base.split_once('?').unwrap_or((base, ""));
    let operation_keys = [
        "SERVICE",
        "REQUEST",
        "VERSION",
        "ACCEPTVERSIONS",
        "TYPENAME",
        "TYPENAMES",
        "COUNT",
        "MAXFEATURES",
        "STARTINDEX",
        "RESULTTYPE",
        "SRSNAME",
        "OUTPUTFORMAT",
    ];
    let mut pairs: Vec<String> = query
        .split('&')
        .filter(|pair| !pair.is_empty())
        .filter(|pair| {
            let name = crate::vfs::decode_query_component(pair.split('=').next().unwrap_or(""));
            !operation_keys.iter().any(|key| name.eq_ignore_ascii_case(key))
                && !values.iter().any(|(key, _)| name.eq_ignore_ascii_case(key))
        })
        .map(str::to_string)
        .collect();
    pairs.extend(values.iter().map(|(key, value)| format!("{key}={}", encode(value))));
    format!("{base}?{}", pairs.join("&"))
}

fn operation_endpoint(root: &Element, operation: &str, source: &str) -> String {
    let mut operations = Vec::new();
    root.find_all("Operation", &mut operations);
    let modern = operations
        .iter()
        .find(|node| node.attr("name") == Some(operation))
        .and_then(|node| node.find("Get"))
        .and_then(|node| node.attr("href"));
    let legacy = root
        .child("Capability")
        .and_then(|n| n.child("Request"))
        .and_then(|n| n.child(operation))
        .and_then(|n| n.find("Get"))
        .and_then(|n| n.attr("onlineResource").or_else(|| n.attr("href")));
    let Some(href) = modern.or(legacy) else { return source.to_string() };
    let mut url = crate::stac::resolve_href(source, href);
    // Public HTTPS proxies sometimes advertise their same-host HTTP backend.
    if source.starts_with("https://")
        && url.starts_with("http://")
        && crate::vfs::url_origin(source).map(|(_, h)| h) == crate::vfs::url_origin(&url).map(|(_, h)| h)
    {
        url = format!("https://{}", &url[7..]);
    }
    if crate::vfs::url_origin(source) != crate::vfs::url_origin(&url) {
        // Keep requests and source authentication at the endpoint the caller chose.
        return source.to_string();
    }
    // Preserve map selectors and authentication query parameters, without forwarding them to
    // another origin. Operation-specific KVP values are replaced by request_url.
    if let Some((_, query)) = source.split('#').next().unwrap_or(source).split_once('?') {
        for pair in query.split('&').filter(|pair| !pair.is_empty()) {
            let key = pair.split('=').next().unwrap_or("");
            if parameter(&url, key).is_none() {
                url.push(if url.contains('?') { '&' } else { '?' });
                url.push_str(pair);
            }
        }
    }
    url
}

fn reserve_parse(bytes: usize, retained: usize) -> Result<()> {
    let peak = bytes.checked_mul(XML_WORKSPACE_FACTOR).and_then(|n| n.checked_add(retained));
    crate::dataset::fallible::check_usable(peak, || "WFS: XML/page parsing exceeds usable memory".into()).map_err(limited)?;
    let needed = bytes.checked_mul(XML_WORKSPACE_FACTOR).ok_or_else(|| limited("page parse estimate overflows"))?;
    // Probe virtual-address-space availability fallibly before the XML parser's
    // infallible allocations. The estimate includes the element tree and decoded strings;
    // physical usable memory is checked above. This is a preflight, not a retained buffer.
    let mut probe = Vec::<u8>::new();
    probe.try_reserve_exact(needed).map_err(|_| limited(format!("cannot reserve estimated page parsing storage for {bytes} bytes")))?;
    Ok(())
}

fn parse_xml(bytes: &[u8], retained: usize) -> Result<Element> {
    reserve_parse(bytes.len(), retained)?;
    let root = xml::parse_strict_limited(&xml::decode(bytes), XML_ELEMENTS)?;
    if matches!(root.name.as_str(), "ExceptionReport" | "ServiceExceptionReport" | "ServiceException") {
        let mut messages = Vec::new();
        root.find_all("ExceptionText", &mut messages);
        root.find_all("ServiceException", &mut messages);
        let message = messages.iter().map(|e| e.text.trim()).filter(|s| !s.is_empty()).collect::<Vec<_>>().join("; ");
        return Err(invalid(if message.is_empty() { "server returned an exception".into() } else { message }));
    }
    Ok(root)
}

fn fetch(url: &str, cap: u64) -> Result<Vec<u8>> {
    crate::http::get_capped_following(&Remote::Url(url.to_string()), cap.min(crate::http::json_max_size()), Redirects::Any)
}

impl Service {
    fn load(source: &str) -> Result<Self> {
        if !(source.starts_with("https://") || source.starts_with("http://")) {
            return Err(Error::InvalidArgument("WFS requires an HTTP(S) endpoint".into()));
        }
        let url = if parameter(source, "request").is_some_and(|v| v.eq_ignore_ascii_case("GetCapabilities")) {
            source.to_string()
        } else {
            let mut kvp = vec![("SERVICE", "WFS".into()), ("REQUEST", "GetCapabilities".into())];
            if let Some(version) = parameter(source, "version") {
                kvp.push(("VERSION", version.into()));
            }
            request_url(source, &kvp)
        };
        let root = parse_xml(&fetch(&url, METADATA_CAP)?, 0)?;
        if root.name != "WFS_Capabilities" {
            return Err(invalid(format!("expected WFS_Capabilities at {}, got {}", safe_url(source), root.name)));
        }
        let ns = root.namespace(&root.prefix);
        if !matches!(ns, Some("http://www.opengis.net/wfs" | "http://www.opengis.net/wfs/2.0")) {
            return Err(invalid("capabilities have no WFS namespace"));
        }
        let version = root.attr("version").ok_or_else(|| invalid("capabilities have no version"))?.to_string();
        if !matches!(version.as_str(), "1.0.0" | "1.1.0" | "2.0.0" | "2.0.2") {
            return Err(Error::Unsupported(format!("WFS: version {version} is not supported")));
        }
        let feature_url = operation_endpoint(&root, "GetFeature", source);
        let schema_url = operation_endpoint(&root, "DescribeFeatureType", source);
        let list = root.child("FeatureTypeList").ok_or_else(|| invalid("capabilities have no FeatureTypeList"))?;
        let mut types = Vec::new();
        for item in list.children_named("FeatureType") {
            let name = item.child_text("Name").ok_or_else(|| invalid("a feature type has no Name"))?.to_string();
            if types.iter().any(|t: &FeatureType| t.name == name) {
                return Err(invalid(format!("duplicate feature type {name}")));
            }
            let srs = item
                .child_text("DefaultCRS")
                .or_else(|| item.child_text("DefaultSRS"))
                .or_else(|| item.child_text("SRS"))
                .map(str::to_string);
            let bbox = item
                .child("WGS84BoundingBox")
                .and_then(|b| {
                    let lo: Vec<f64> =
                        b.child_text("LowerCorner")?.split_whitespace().map(str::parse).collect::<std::result::Result<_, _>>().ok()?;
                    let hi: Vec<f64> =
                        b.child_text("UpperCorner")?.split_whitespace().map(str::parse).collect::<std::result::Result<_, _>>().ok()?;
                    (lo.len() == 2 && hi.len() == 2).then(|| [lo[0], lo[1], hi[0], hi[1]])
                })
                .or_else(|| {
                    item.child("LatLongBoundingBox").and_then(|b| {
                        Some([
                            b.attr("minx")?.parse().ok()?,
                            b.attr("miny")?.parse().ok()?,
                            b.attr("maxx")?.parse().ok()?,
                            b.attr("maxy")?.parse().ok()?,
                        ])
                    })
                })
                .filter(|b| b.iter().all(|v| v.is_finite()) && b[0] <= b[2] && b[1] <= b[3]);
            let namespace = if let Some((prefix, _)) = name.split_once(':') {
                let node = item.child("Name").unwrap();
                Some(
                    node.namespace(prefix)
                        .or_else(|| item.namespace(prefix))
                        .or_else(|| list.namespace(prefix))
                        .or_else(|| root.namespace(prefix))
                        .filter(|uri| !uri.is_empty())
                        .ok_or_else(|| invalid(format!("feature type {name} has an unbound namespace prefix")))?
                        .to_string(),
                )
            } else {
                None
            };
            types.push(FeatureType { name, namespace, title: item.child_text("Title").map(str::to_string), srs, wgs84: bbox });
        }
        let mut constraints = Vec::new();
        root.find_all("Constraint", &mut constraints);
        let paging = constraints
            .iter()
            .find(|n| n.attr("name") == Some("ImplementsResultPaging"))
            .and_then(|n| n.child_text("DefaultValue"))
            .map(|v| v.eq_ignore_ascii_case("true") || v == "1");
        Ok(Self { source: source.to_string(), version, feature_url, schema_url, paging, types })
    }

    fn info(&self) -> ServiceInfo {
        ServiceInfo {
            driver: "WFS".into(),
            version: self.version.clone(),
            metadata_only: true,
            layers: self
                .types
                .iter()
                .map(|t| {
                    let crs = t.srs.as_deref().and_then(|s| SpatialRef::parse(s).ok());
                    let crs = crs.as_ref().map(CrsSummary::new).unwrap_or(CrsSummary { epsg: None, name: None, wkt: None, esri: None });
                    ServiceLayerInfo {
                        name: t.name.clone(),
                        title: t.title.clone(),
                        geometry_type: "Unknown".into(),
                        feature_count: None,
                        crs,
                        extent: None,
                        wgs84_extent: t.wgs84,
                        fields: Vec::new(),
                    }
                })
                .collect(),
        }
    }

    fn request(&self, operation: &str, feature: &FeatureType) -> Vec<(&'static str, String)> {
        vec![
            ("SERVICE", "WFS".into()),
            ("VERSION", self.version.clone()),
            ("REQUEST", operation.into()),
            (if self.version.starts_with('2') { "TYPENAMES" } else { "TYPENAME" }, feature.name.clone()),
        ]
    }
}

pub(crate) fn info(source: &str) -> Result<ServiceInfo> {
    Ok(Service::load(source)?.info())
}
pub(crate) fn list_layers(source: &str) -> Result<Vec<String>> {
    Ok(Service::load(source)?.types.into_iter().map(|t| t.name).collect())
}

pub(crate) fn feature_exception(bytes: &[u8]) -> Error {
    parse_xml(bytes, 0).err().unwrap_or_else(|| invalid("the service refused GetFeature"))
}

struct Budget {
    used: usize,
    limit: usize,
}
impl Budget {
    fn preflight_dense(&self, rows: usize, fields: usize, page_bytes: usize) -> Result<()> {
        let cells = rows.checked_mul(fields).ok_or_else(|| limited("dense field matrix size overflows"))?;
        let dense = cells
            .checked_mul(size_of::<FieldValue>())
            .and_then(|n| rows.checked_mul(size_of::<Feature>() * 2).and_then(|features| n.checked_add(features)))
            .ok_or_else(|| limited("dense field matrix size overflows"))?;
        let retained = self
            .used
            .checked_add(dense)
            .filter(|n| *n <= self.limit)
            .ok_or_else(|| limited(format!("dense field matrix exceeds WFS_MAX_VECTOR_BYTES={}", self.limit)))?;
        let peak = page_bytes.checked_mul(XML_WORKSPACE_FACTOR).and_then(|n| n.checked_add(retained));
        crate::dataset::fallible::check_usable(peak, || "WFS: dense field matrix exceeds usable memory".into()).map_err(limited)?;
        // GML allocates a dense row even for absent properties. Check that matrix
        // fallibly before entering the decoder, then release the temporary reservation.
        let mut probe = Vec::<FieldValue>::new();
        probe.try_reserve_exact(cells).map_err(|_| limited("cannot reserve dense field matrix"))?;
        Ok(())
    }
    fn charge(&mut self, bytes: usize) -> Result<()> {
        self.used = self
            .used
            .checked_add(bytes)
            .filter(|n| *n <= self.limit)
            .ok_or_else(|| limited(format!("retained vector estimate exceeds WFS_MAX_VECTOR_BYTES={}", self.limit)))?;
        Ok(())
    }
}
fn ring_heap(r: &Ring) -> usize {
    r.0.capacity().saturating_mul(size_of::<Coord>())
}
fn geometry_heap(g: &Geometry) -> usize {
    let coords = |v: &Vec<Coord>| v.capacity().saturating_mul(size_of::<Coord>());
    match g {
        Geometry::Point(_) => 0,
        Geometry::LineString(v) | Geometry::MultiPoint(v) => coords(v),
        Geometry::Polygon { exterior, interiors } => ring_heap(exterior)
            .saturating_add(interiors.capacity().saturating_mul(size_of::<Ring>()))
            .saturating_add(interiors.iter().map(ring_heap).fold(0usize, usize::saturating_add)),
        Geometry::MultiLineString(v) => {
            v.capacity().saturating_mul(size_of::<Vec<Coord>>()).saturating_add(v.iter().map(coords).fold(0usize, usize::saturating_add))
        }
        Geometry::MultiPolygon(v) => v.capacity().saturating_mul(size_of::<(Ring, Vec<Ring>)>()).saturating_add(
            v.iter()
                .map(|(e, hs)| {
                    ring_heap(e)
                        .saturating_add(hs.capacity().saturating_mul(size_of::<Ring>()))
                        .saturating_add(hs.iter().map(ring_heap).fold(0usize, usize::saturating_add))
                })
                .fold(0usize, usize::saturating_add),
        ),
        Geometry::GeometryCollection(v) => v
            .capacity()
            .saturating_mul(size_of::<Geometry>())
            .saturating_add(v.iter().map(geometry_heap).fold(0usize, usize::saturating_add)),
    }
}
fn layer_bytes(layer: &Layer) -> usize {
    let mut bytes = layer.name.capacity().saturating_add(layer.features.capacity().saturating_mul(size_of::<Feature>()).saturating_mul(2));
    for field in layer.schema.fields() {
        bytes = bytes.saturating_add(size_of::<FieldDef>() * 2).saturating_add(field.name.capacity());
    }
    for f in &layer.features {
        bytes = bytes.saturating_add(f.attributes.capacity().saturating_mul(size_of::<FieldValue>()));
        for v in &f.attributes {
            bytes = bytes.saturating_add(match v {
                FieldValue::Text(s) | FieldValue::Date(s) | FieldValue::DateTime(s) => s.capacity(),
                FieldValue::Blob(b) => b.capacity(),
                _ => 0,
            });
        }
        if let Some(g) = &f.geometry {
            bytes = bytes.saturating_add(geometry_heap(g));
        }
    }
    bytes
}

fn declared_geometry(schema: &Element, local: &str) -> Result<Option<GeometryType>> {
    Ok(gml::xsd_elements(schema, local)?.into_iter().filter_map(|(_, kind, geometry)| geometry.then_some(kind)).find_map(|kind| {
        let kind = kind.rsplit(':').next()?;
        Some(match kind {
            "PointPropertyType" => GeometryType::Point,
            "LineStringPropertyType" | "CurvePropertyType" => GeometryType::LineString,
            "PolygonPropertyType" | "SurfacePropertyType" => GeometryType::Polygon,
            "MultiPointPropertyType" => GeometryType::MultiPoint,
            "MultiLineStringPropertyType" | "MultiCurvePropertyType" => GeometryType::MultiLineString,
            "MultiPolygonPropertyType" | "MultiSurfacePropertyType" => GeometryType::MultiPolygon,
            _ => return None,
        })
    }))
}

fn empty_layer(name: &str, schema: &Element, srs: Option<&str>) -> Result<Layer> {
    let local = name.rsplit(':').next().unwrap_or(name);
    let mut layer = Layer::new(name);
    layer.add_field(FieldDef::new("gml_id", FieldType::Text));
    for (name, kind) in gml::xsd_fields(schema, local)? {
        layer.add_field(FieldDef::new(name, kind));
    }
    layer.geom_type = declared_geometry(schema, local)?;
    if let Some(s) = srs.and_then(|s| SpatialRef::parse(s).ok()) {
        s.apply_to_layer(&mut layer);
    }
    Ok(layer)
}

// The general GML reader is deliberately permissive. A service must not silently drop
// properties or linearize unsupported curves when it claims to return simple features.
fn validate_simple(feature: &Element, layer: &Layer, expected_crs: Option<&SpatialRef>, page_srs: Option<&str>) -> Result<()> {
    fn geometry_tree(node: &Element, expected_crs: Option<&SpatialRef>, page_srs: Option<&str>) -> Result<()> {
        if let Some(srs) = node.attr("srsName")
            && Some(srs) != page_srs
        {
            let actual = SpatialRef::parse(srs).map_err(|_| invalid("a geometry declares an unrecognized CRS"))?;
            if expected_crs.is_some_and(|expected| !expected.same_as(&actual)) {
                return Err(invalid("a geometry CRS differs from the requested layer CRS"));
            }
            if actual.is_geographic() && page_srs.is_some_and(|reference| gml::lat_lon_order(reference) != gml::lat_lon_order(srs)) {
                return Err(invalid("mixed geometry axis orders within a page are unsupported"));
            }
        }
        if node.attr("href").is_some()
            || node.name == "segments" && node.children.iter().any(|child| child.name != "LineStringSegment")
            || matches!(
                node.name.as_str(),
                "Arc"
                    | "ArcString"
                    | "Circle"
                    | "CircleByCenterPoint"
                    | "ArcByCenterPoint"
                    | "CubicSpline"
                    | "BSpline"
                    | "Bezier"
                    | "Clothoid"
                    | "Geodesic"
                    | "GeodesicString"
                    | "OffsetCurve"
            )
            || node.attr("orientation") == Some("-")
            || node.name == "patches" && node.children.len() > 1
        {
            return Err(Error::Unsupported("WFS: linked, curved or composite surface geometries are not supported".into()));
        }
        for child in &node.children {
            geometry_tree(child, expected_crs, page_srs)?;
        }
        Ok(())
    }
    if feature.name != layer.name.rsplit(':').next().unwrap_or(&layer.name) {
        return Err(invalid("GetFeature returned a different feature type"));
    }
    let mut names = std::collections::HashSet::new();
    let mut geometries = 0;
    for property in &feature.children {
        if property.name == "boundedBy" {
            continue;
        }
        if !names.insert(property.name.as_str()) || property.attr("href").is_some() {
            return Err(Error::Unsupported("WFS: repeated or linked feature properties are not supported".into()));
        }
        if property.children.is_empty() {
            if layer.schema.field_index(&property.name).is_none() && !matches!(property.attr("nil"), Some("true" | "1")) {
                return Err(invalid(format!("undeclared property {}", property.name)));
            }
        } else {
            if property.children.len() != 1 || !gml::GEOMETRIES.contains(&property.children[0].name.as_str()) {
                return Err(Error::Unsupported("WFS: complex feature properties are not supported".into()));
            }
            if layer.schema.field_index(&property.name).is_some() {
                return Err(invalid("a geometry was supplied for a declared scalar property"));
            }
            geometries += 1;
            if geometries > 1 {
                return Err(Error::Unsupported("WFS: multiple geometry properties are not supported".into()));
            }
            geometry_tree(&property.children[0], expected_crs, page_srs)?;
            if gml::geometry(&property.children[0], 2).is_none() {
                return Err(invalid("a geometry property could not be decoded"));
            }
        }
    }
    Ok(())
}

fn read_type(service: &Service, feature: &FeatureType, options: &VectorOpenOptions, budget: &mut Budget) -> Result<Layer> {
    let schema_kvp = service.request("DescribeFeatureType", feature);
    let schema = parse_xml(&fetch(&request_url(&service.schema_url, &schema_kvp), METADATA_CAP)?, budget.used)?;
    if schema.name != "schema" {
        return Err(invalid("DescribeFeatureType did not return an XML schema"));
    }
    let namespace = feature.namespace.as_deref().or_else(|| schema.attr("targetNamespace"));
    if feature.namespace.as_deref().is_some_and(|ns| schema.attr("targetNamespace") != Some(ns)) {
        return Err(invalid("DescribeFeatureType returned a different feature namespace"));
    }
    let mut expected_crs = feature.srs.as_deref().and_then(|s| SpatialRef::parse(s).ok());
    let mut layer = empty_layer(&feature.name, &schema, feature.srs.as_deref())?;
    budget.charge(layer_bytes(&layer))?;
    if options.max_features == Some(0) {
        return Ok(layer);
    }
    let paging = options.wfs.paging.unwrap_or(service.version.starts_with('2') && service.paging != Some(false));
    let single_page = options.wfs.paging == Some(false);
    let mut offset = if paging { options.skip_features } else { 0 };
    let mut previous_range: Option<(usize, usize)> = None;
    loop {
        let mut kvp = service.request("GetFeature", feature);
        let remaining = options.max_features.map(|n| n.saturating_sub(layer.features.len()));
        let count = if paging {
            Some(remaining.map_or(options.wfs.page_size, |n| n.min(options.wfs.page_size)))
        } else if single_page {
            Some(options.skip_features.saturating_add(options.max_features.unwrap_or(options.wfs.page_size)))
        } else {
            options.max_features.map(|n| options.skip_features.saturating_add(n))
        };
        if let Some(n) = count {
            kvp.push((if service.version.starts_with('2') { "COUNT" } else { "MAXFEATURES" }, n.to_string()));
        }
        if paging {
            kvp.push(("STARTINDEX", offset.to_string()));
        }
        if let Some(srs) = &feature.srs {
            kvp.push(("SRSNAME", srs.clone()));
        }
        if let Some((xmin, ymin, xmax, ymax)) = options.spatial_filter {
            let swap = !service.version.starts_with("1.0")
                && feature.srs.as_deref().is_some_and(gml::lat_lon_order)
                && feature.srs.as_deref().and_then(|s| SpatialRef::parse(s).ok()).is_some_and(|s| s.is_geographic());
            let mut bbox = if swap { format!("{ymin},{xmin},{ymax},{xmax}") } else { format!("{xmin},{ymin},{xmax},{ymax}") };
            if let Some(srs) = &feature.srs {
                bbox.push(',');
                bbox.push_str(srs);
            }
            kvp.push(("BBOX", bbox));
        }
        let url = request_url(&service.feature_url, &kvp);
        let bytes = fetch(&url, PAGE_CAP)?;
        let (mut page, matched) = if bytes.iter().find(|b| !b.is_ascii_whitespace()).is_some_and(|b| *b == b'{') {
            return Err(Error::Unsupported("WFS: this service returned GeoJSON instead of GML; open its GetFeature URL directly".into()));
        } else {
            let root = parse_xml(&bytes, budget.used)?;
            if root.name != "FeatureCollection" {
                return Err(invalid(format!("GetFeature returned {}, not a feature collection", root.name)));
            }
            let page_srs = gml::collection_srs_name(&root);
            if let Some(srs) = page_srs {
                let actual = SpatialRef::parse(srs).map_err(|_| invalid("a geometry declares an unrecognized CRS"))?;
                if expected_crs.as_ref().is_some_and(|expected| !expected.same_as(&actual)) {
                    return Err(invalid("a geometry CRS differs from the requested layer CRS"));
                }
                if expected_crs.is_none() {
                    expected_crs = Some(actual);
                }
            }
            let matched = root.attr("numberMatched").and_then(|n| n.parse::<usize>().ok());
            let mut rows = 0usize;
            for member in &root.children {
                if matches!(member.name.as_str(), "member" | "featureMember") && member.children.len() > 1 {
                    return Err(invalid("a feature member contains multiple features"));
                }
                if matches!(member.name.as_str(), "member" | "featureMember" | "featureMembers") {
                    rows = rows.checked_add(member.children.len()).ok_or_else(|| limited("feature count overflows"))?;
                    for feature in &member.children {
                        // Collection/member/feature are the only namespace scopes on this
                        // known path. Avoid rescanning earlier features for every row.
                        let prefix = &feature.prefix;
                        let actual = feature
                            .namespace(prefix)
                            .or_else(|| member.namespace(prefix))
                            .or_else(|| root.namespace(prefix))
                            .filter(|s| !s.is_empty());
                        if actual != namespace {
                            return Err(invalid("GetFeature returned a different feature namespace"));
                        }
                        validate_simple(feature, &layer, expected_crs.as_ref(), page_srs)?;
                    }
                }
            }
            budget.preflight_dense(rows, layer.schema.fields().len(), bytes.len())?;
            let page = if rows > 0 {
                let mut layers = gml::parse(&root, Some(&schema))?;
                if layers.len() != 1 {
                    return Err(invalid("a single-type request returned multiple feature types"));
                }
                layers.remove(0)
            } else {
                empty_layer(&feature.name, &schema, feature.srs.as_deref())?
            };
            (page, matched)
        };
        if page.features.is_empty() {
            if matched.is_some_and(|total| offset < total) {
                return Err(invalid(format!("empty page at offset {offset} before the advertised feature count")));
            }
            break;
        }
        if paging && matched.is_some_and(|total| offset.saturating_add(page.features.len()) > total) {
            return Err(invalid("numberMatched is smaller than the returned feature range"));
        }
        if paging
            && previous_range.is_some_and(|(start, len)| {
                len == page.features.len()
                    && layer.features[start..start + len].iter().zip(&page.features).all(|(a, b)| {
                        match (a.attributes.first(), b.attributes.first()) {
                            (Some(FieldValue::Text(a)), Some(FieldValue::Text(b))) => a == b,
                            _ => a.attributes == b.attributes && a.geometry == b.geometry,
                        }
                    })
            })
        {
            return Err(invalid(format!("page at offset {offset} repeats the previous page; the server ignores STARTINDEX")));
        }
        let expected: Vec<_> = layer.schema.fields().iter().map(|f| (&f.name, f.field_type)).collect();
        let actual: Vec<_> = page.schema.fields().iter().map(|f| (&f.name, f.field_type)).collect();
        if actual != expected {
            return Err(invalid("GetFeature schema differs from DescribeFeatureType"));
        }
        if layer.crs.is_none() {
            layer.crs = page.crs.take();
        }
        if layer
            .geom_type
            .is_some_and(|declared| page.features.iter().filter_map(|f| f.geometry.as_ref()).any(|g| g.geom_type() != declared))
        {
            // A schema hint must not override the geometries actually returned. None
            // lets the standard layer reporter infer/promote types across all pages.
            layer.geom_type = None;
        }
        let returned = page.features.len();
        if let Some(left) = remaining.filter(|_| paging) {
            page.features.truncate(left);
        }
        for (i, f) in page.features.iter_mut().enumerate() {
            f.fid = offset.saturating_add(i) as u64;
        }
        budget.charge(layer_bytes(&page))?;
        layer.features.try_reserve_exact(page.features.len()).map_err(|_| limited("cannot retain another feature page"))?;
        previous_range = Some((layer.features.len(), page.features.len()));
        layer.features.append(&mut page.features);
        layer.extent = None;
        offset = offset.checked_add(returned).ok_or_else(|| limited("feature offset overflow"))?;
        if !paging && options.max_features.is_none() && matched.is_some_and(|total| offset < total) {
            crate::warnings::warn(format!(
                "WFS: {} returned {offset} of {} matching features with paging disabled; enable WFS_PAGING=YES to read the rest",
                feature.name,
                matched.unwrap()
            ));
        }
        if !paging || options.max_features.is_some_and(|max| layer.features.len() >= max) || matched.is_some_and(|total| offset >= total) {
            break;
        }
    }
    if !paging {
        options.keep_range(&mut layer);
    }
    Ok(layer)
}

pub(crate) fn open(source: &str, options: &VectorOpenOptions) -> Result<VectorDataset> {
    if options.wfs.page_size == 0 || options.wfs.max_vector_bytes == 0 {
        return Err(Error::InvalidArgument("WFS_PAGE_SIZE and WFS_MAX_VECTOR_BYTES must be positive".into()));
    }
    let service = Service::load(source)?;
    let selected: Vec<_> = if options.layers.is_empty() {
        service.types.iter().collect()
    } else {
        let mut selected = Vec::new();
        for wanted in &options.layers {
            let matches: Vec<_> =
                service.types.iter().filter(|t| t.name == *wanted || t.name.rsplit(':').next() == Some(wanted.as_str())).collect();
            if matches.len() != 1 {
                return Err(Error::InvalidArgument(format!("WFS: layer {wanted:?} is missing or ambiguous")));
            }
            if !selected.iter().any(|t: &&FeatureType| t.name == matches[0].name) {
                selected.push(matches[0]);
            }
        }
        selected
    };
    let mut budget = Budget { used: 0, limit: options.wfs.max_vector_bytes };
    let mut layers = Vec::new();
    for feature in selected {
        layers.push(read_type(&service, feature, options, &mut budget)?);
    }
    Ok(crate::dataset::finish_vector(layers, safe_url(&service.source), VectorDriver::WFS))
}
