//! Bounded folder generation. Tile sinks let WASM clients consume tiles incrementally.
use super::*;
use crate::crs::SpatialRef;
use crate::ops::{
    Resampling,
    warp::{Nodata, WarpOptions, WarpSource, WarpSourceInfo},
};
use crate::{DataType, RasterDataset, RasterWriteOptions, Window, WindowOptions};
use wbraster::raster::RasterData;

/// Folder generation options. Lower zooms are resampled directly from the source,
/// independently of previously encoded tiles, retaining bounded tile-sized output.
#[derive(Debug, Clone, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct TileOptions {
    /// `WebMercatorQuad`, `WorldCRS84Quad`, or `raster` (source CRS/grid).
    #[serde(alias = "tilingScheme")]
    pub tiling_scheme: String,
    /// Pixel size, zoom range and optional coordinate restrictions.
    pub grid: GridOptions,
    /// XYZ (north-origin) or TMS (south-origin) filename rows.
    pub convention: Convention,
    /// PNG or GTiff output. GTiff retains arbitrary band counts and sample types.
    pub format: String,
    /// Maximum-zoom resampling (nearest, bilinear, cubic, etc.).
    pub resampling: String,
    /// Lower-zoom resampling; defaults to maximum-zoom resampling.
    #[serde(alias = "overviewResampling")]
    pub overview_resampling: Option<String>,
    /// Add an alpha band. PNG defaults to alpha only on tiles with transparency.
    /// False removes existing alpha too.
    pub alpha: Option<bool>,
    /// Background for invalid pixels, including color beneath transparent alpha.
    #[serde(alias = "outputNodata")]
    pub output_nodata: Option<f64>,
    /// Omit fully transparent or nodata-only tiles.
    #[serde(alias = "skipBlank")]
    pub skip_blank: bool,
    /// Refuse plans exceeding this many tiles before reading pixels.
    #[serde(alias = "maxTiles")]
    pub max_tiles: u64,
    /// Optional viewer, KML, MapML and STACTA companions.
    pub publication: crate::ops::raster_publication::PublicationOptions,
}
impl Default for TileOptions {
    fn default() -> Self {
        Self {
            tiling_scheme: "WebMercatorQuad".into(),
            grid: GridOptions::default(),
            convention: Convention::Xyz,
            format: "PNG".into(),
            resampling: "cubic".into(),
            overview_resampling: None,
            alpha: None,
            output_nodata: None,
            skip_blank: false,
            max_tiles: 1_000_000,
            publication: Default::default(),
        }
    }
}

/// Result counters; no tile images are retained here.
#[derive(Debug, Default, Serialize)]
pub struct TileReport {
    /// Tiles in the plan.
    pub planned: u64,
    /// Tiles sent to the sink.
    pub written: u64,
    /// Transparent/nodata tiles omitted.
    pub blank: u64,
    /// Existing tiles left untouched by resume.
    pub resumed: u64,
}

/// An incremental destination for encoded tiles. Names are generated by Terrio and
/// contain only numeric coordinates and a fixed extension.
pub trait FolderSink {
    /// Whether this tile is already present (used by resume). Default: no.
    fn exists(&mut self, _name: &str) -> Result<bool> {
        Ok(false)
    }
    /// Read a previously emitted file, when storage supports it. Retile pyramids
    /// use this for parent tiles; write-only sinks regenerate parents with a bounded cache.
    fn get(&mut self, _name: &str) -> Result<Option<Vec<u8>>> {
        Ok(None)
    }
    /// Consume one encoded tile. Called after rendering and encoding complete.
    fn put(&mut self, name: &str, bytes: &[u8]) -> Result<()>;
}

fn format(options: &TileOptions) -> Result<(crate::formats::RasterDriver, &'static str)> {
    use crate::formats::RasterDriver;
    match options.format.to_ascii_lowercase().as_str() {
        "png" => Ok((RasterDriver::PNG, "png")),
        "gtiff" | "tiff" | "tif" => Ok((RasterDriver::GTiff, "tif")),
        _ => Err(Error::Unsupported("folder tiles support PNG and GTiff".into())),
    }
}

/// Plan from source metadata only. Global schemes use the warp engine's suggested
/// output resolution and densified source perimeter; raster grids require north-up affine input.
/// Validates rendering choices available from metadata, without reading source pixels.
pub fn plan(source: &RasterDataset, options: &TileOptions) -> Result<(TilePlan, Option<SpatialRef>)> {
    let (_, extension) = format(options)?;
    let r = &source.raster;
    if source.complex || r.bands == 0 {
        return Err(Error::Unsupported("folder tiles require non-complex raster bands".into()));
    }
    if source.geolocation.is_some() || !source.gcps.is_empty() {
        return Err(Error::Unsupported("folder tiling currently requires affine georeferencing".into()));
    }
    validate_rendering(source, options, extension)?;
    let validate_publication = |plan: &TilePlan| {
        crate::ops::raster_publication::Publication::new(
            plan,
            source,
            &options.publication,
            &options.tiling_scheme,
            options.convention,
            extension,
        )
        .map(|_| ())
    };
    let scheme = options.tiling_scheme.to_ascii_lowercase();
    if scheme == "raster" {
        let mut plan = TilePlan::raster(r.cols, r.rows, source.geo_transform(), &options.grid)?;
        let crs = source.crs();
        plan.crs = crs.authority_code().or_else(|| crs.to_wkt()).or(crs.proj4);
        validate_publication(&plan)?;
        return Ok((plan, None));
    }
    if source.crs().is_unknown() {
        return Err(invalid("global tile schemes require a source CRS"));
    }
    let (scheme, crs) = match scheme.as_str() {
        "webmercatorquad" => (GlobalScheme::WebMercatorQuad, SpatialRef::from_epsg(3857)?),
        "worldcrs84quad" => (GlobalScheme::WorldCrs84Quad, SpatialRef::from_epsg(4326)?),
        _ => return Err(Error::Unsupported("tiling scheme must be raster, WebMercatorQuad or WorldCRS84Quad".into())),
    };
    let (gt, w, h) = crate::ops::warp::suggested_grid(r.cols, r.rows, source.geo_transform(), &source.crs(), &crs)?;
    let extent = [gt[0], gt[3] + h as f64 * gt[5], gt[0] + w as f64 * gt[1], gt[3]];
    let plan = TilePlan::global(scheme, extent, gt[1].abs(), &options.grid)?;
    validate_publication(&plan)?;
    Ok((plan, Some(crs)))
}

fn validate_rendering(source: &RasterDataset, options: &TileOptions, extension: &str) -> Result<(bool, bool, [Resampling; 2])> {
    let source_alpha = source.band_color_interp(source.raster.bands).eq_ignore_ascii_case("Alpha");
    let alpha = options.alpha.unwrap_or(extension == "png" || source_alpha);
    let color = extension == "png" || alpha || source_alpha;
    let methods = [
        Resampling::parse(&options.resampling)?,
        Resampling::parse(options.overview_resampling.as_deref().unwrap_or(&options.resampling))?,
    ];
    if color
        && methods.iter().any(|m| {
            !matches!(
                m,
                Resampling::Nearest
                    | Resampling::Bilinear
                    | Resampling::Cubic
                    | Resampling::CubicSpline
                    | Resampling::Lanczos
                    | Resampling::Average
            )
        })
    {
        return Err(Error::Unsupported(
            "alpha/image tiles support nearest, bilinear, cubic, cubicspline, lanczos and average resampling".into(),
        ));
    }
    if extension == "png" && source.raster.data_type != DataType::U8 {
        return Err(Error::Unsupported("PNG tiles require Byte input; scale/translate the raster first, or use GTiff".into()));
    }
    if color {
        if matches!(source.raster.data_type, DataType::U64 | DataType::I64) {
            return Err(Error::Unsupported("image/alpha tiles cannot preserve 64-bit integer samples; use GTiff without alpha".into()));
        }
        color_bands(source)?;
    }
    if let Some(value) = options.output_nodata {
        let dtype = source.raster.data_type;
        let (min, max) = if dtype == DataType::F32 { (-(f32::MAX as f64), f32::MAX as f64) } else { crate::ops::type_range(dtype) };
        if !value.is_finite() || value < min || value > max || (crate::ops::is_integer(dtype) && value.fract() != 0.0) {
            return Err(invalid("output_nodata must be finite and representable in the output sample type"));
        }
        if extension == "tif" && !alpha && dtype == DataType::F32 && value as f32 as f64 != value {
            return Err(invalid("output_nodata must be exactly representable as Float32 for GeoTIFF tiles"));
        }
    }
    Ok((alpha, color, methods))
}

/// Generates encoded tiles incrementally; source windows and output buffers are bounded.
/// Existing source overviews are selected automatically. Lower zooms resample the source
/// directly (not the previously generated pyramid). Sink failures stop generation.
pub fn generate(source: &mut dyn WarpSource, options: &TileOptions, sink: &mut dyn FolderSink) -> Result<TileReport> {
    let info = source.info()?;
    let (plan, dst_srs) = plan(&info.raster, options)?;
    let (driver, extension) = format(options)?;
    let planned = plan.count()?;
    if planned > options.max_tiles {
        return Err(invalid("the plan exceeds max_tiles"));
    }
    let (alpha, color, methods) = validate_rendering(&info.raster, options, extension)?;
    let publication = crate::ops::raster_publication::Publication::new(
        &plan,
        &info.raster,
        &options.publication,
        &options.tiling_scheme,
        options.convention,
        extension,
    )?;
    let preserve_mask = extension == "tif" && !alpha && source.has_mask()?;
    let limits = RenderLimits::default();
    let mut report = TileReport { planned, ..Default::default() };
    for level in &plan.levels {
        let method = methods[usize::from(level.matrix.zoom != plan.max_zoom)];
        for cell in level.cells(options.convention) {
            let name = format!("{}/{}/{}.{}", cell.zoom, cell.x, cell.y, extension);
            if sink.exists(&name)? {
                report.resumed += 1;
                publication.cell(&cell, true, sink)?;
                continue;
            }
            let mut warp = WarpOptions {
                dst_srs: dst_srs.clone(),
                resampling: method,
                kernel_version: crate::ops::warp::KernelVersion::Gdal313,
                error_threshold: 0.0,
                ..Default::default()
            };
            let mut color_blank = false;
            let mut output_mask = None;
            let mut tile = if color {
                warp.src_nodata = Nodata::None;
                // Zero is a valid synthetic color/density sample. Declaring it
                // nodata makes the warp kernel nudge it to the next float.
                warp.dst_nodata = Nodata::None;
                let mut prepared = ColorSource { source, info: info.clone(), only_alpha: false, limits };
                let premult = render_cell(&mut prepared, &cell, &warp, limits)?;
                let n = premult.raster.cols * premult.raster.rows;
                color_blank = (0..n).all(|i| premult.raster.data.get_f64((premult.raster.bands - 1) * n + i) == 0.0);
                finish_color(&premult, info.raster.raster.data_type, alpha, options.output_nodata)?
            } else {
                warp.dst_nodata = options.output_nodata.map_or(Nodata::None, |value| Nodata::Values(vec![value]));
                let mut out = render_cell(source, &cell, &warp, limits)?;
                if options.output_nodata.is_none() {
                    out.has_nodata = info.raster.has_nodata;
                    out.raster.nodata = info.raster.raster.nodata;
                    out.band_nodata = info.raster.band_nodata.clone();
                }
                out
            };
            if (options.skip_blank && !color) || preserve_mask {
                // The output's zero padding is distinct from its source nodata tag.
                // Render validity independently so valid zero-valued tiles survive.
                let mut coverage = ColorSource { source, info: info.clone(), only_alpha: true, limits };
                let coverage_options = WarpOptions {
                    src_nodata: Nodata::None,
                    dst_nodata: Nodata::None,
                    resampling: if method == Resampling::Nearest { Resampling::Nearest } else { Resampling::Max },
                    ..warp.clone()
                };
                let density = render_cell(&mut coverage, &cell, &coverage_options, limits)?;
                color_blank = (0..density.raster.data.len()).all(|i| density.raster.data.get_f64(i) == 0.0);
                if preserve_mask {
                    output_mask =
                        Some((0..density.raster.data.len()).map(|i| if density.raster.data.get_f64(i) != 0.0 { 255 } else { 0 }).collect());
                }
            }
            // GDAL omits an automatically generated alpha channel on fully opaque tiles.
            if extension == "png" && options.alpha.is_none() && !publication.fixed_alpha() {
                let n = tile.raster.cols * tile.raster.rows;
                let bands = tile.raster.bands;
                if (0..n).all(|i| tile.raster.data.get_f64((bands - 1) * n + i) == 255.0) {
                    let data = RasterData::U8((0..n * (bands - 1)).map(|i| tile.raster.data.get_f64(i) as u8).collect());
                    let metadata = tile.band_metadata[..bands - 1].to_vec();
                    tile = crate::ops::derived(&tile, data, bands - 1)?;
                    tile.band_metadata = metadata;
                }
            }
            if options.skip_blank && color_blank {
                report.blank += 1;
                publication.cell(&cell, false, sink)?;
                continue;
            }
            // Image metadata/georeferencing cannot be embedded in PNG; the compact tile
            // plan is available separately through the planning API.
            if extension == "png" {
                tile.raster.metadata.clear();
            }
            let bytes = if extension == "png" {
                encode_png(&tile)?
            } else {
                if crate::dataset::needs_nodata_pam(&tile) {
                    return Err(Error::Unsupported("folder GeoTIFF tiles currently require a single shared nodata value".into()));
                }
                crate::memory::write_raster_bytes(
                    &tile,
                    &name,
                    &RasterWriteOptions { driver: Some(driver), mask: output_mask, ..Default::default() },
                )?
            };
            sink.put(&name, &bytes)?;
            report.written += 1;
            publication.cell(&cell, true, sink)?;
        }
    }
    let mut published = info.raster.clone();
    if color {
        published.raster.bands = color_bands(&info.raster)? + usize::from(alpha);
    }
    if extension == "png" {
        published.raster.data_type = DataType::U8;
    }
    publication.finish(&published, sink)?;
    Ok(report)
}

/// Premultiplied Float64 data and alpha are resampled together. Zero-alpha pixels
/// contribute zero density and cannot bleed their colors into neighboring pixels.
/// Per-band densities also exclude each channel's nodata before normalization.
struct ColorSource<'a> {
    source: &'a mut dyn WarpSource,
    info: WarpSourceInfo,
    only_alpha: bool,
    limits: RenderLimits,
}
impl WarpSource for ColorSource<'_> {
    fn info(&mut self) -> Result<WarpSourceInfo> {
        let mut info = self.info.clone();
        let ds = &mut info.raster;
        let bands = if self.only_alpha { 0 } else { color_bands(ds)? };
        let output_bands = if self.only_alpha { 1 } else { 2 * bands + 1 };
        ds.raster.bands = output_bands;
        ds.raster.data_type = DataType::F64;
        ds.has_nodata = false;
        ds.band_nodata = vec![None; output_bands];
        ds.band_metadata.clear();
        ds.color_table.clear();
        Ok(info)
    }
    fn read_window(&mut self, window: Window, options: &WindowOptions) -> Result<RasterDataset> {
        if !options.bands.is_empty() {
            return Err(invalid("premultiplied tile source requires all bands"));
        }
        let header = &self.info.raster.raster;
        let bytes = window
            .width
            .checked_mul(window.height)
            .and_then(|n| n.checked_mul(header.bands))
            .and_then(|n| n.checked_mul(header.data_type.size_bytes()));
        if bytes.is_none_or(|n| n > self.limits.max_source_window_bytes) {
            return Err(Error::Unsupported("source tile window exceeds the pixel-buffer budget".into()));
        }
        let input = self.source.read_window(window, &WindowOptions { bands: vec![], ..options.clone() })?;
        let mask = self.source.read_mask(window, options.overview)?;
        let expanded;
        let ds = if !input.color_table.is_empty() {
            expanded = crate::ops::palette::palette_to_rgb(&input, true)?;
            &expanded
        } else {
            &input
        };
        let bands = data_bands(ds);
        let output_bands = if self.only_alpha { 1 } else { 2 * bands + 1 };
        let n = window.width * window.height;
        if mask.as_ref().is_some_and(|m| m.len() != n) {
            return Err(invalid("source tile mask length does not match the window"));
        }
        let band_nodata: Vec<_> = (1..=bands).map(|b| ds.band_nodata(b)).collect();
        let mut values = vec![0.0; n * output_bands];
        for i in 0..n {
            let invalid_band = |b: usize| {
                band_nodata[b].is_some_and(|nd| {
                    let v = ds.raster.data.get_f64(b * n + i);
                    v == nd || (v.is_nan() && nd.is_nan())
                })
            };
            let nodata = (0..bands).all(invalid_band);
            let a = if nodata || mask.as_ref().is_some_and(|m| m[i] == 0) {
                0.0
            } else if bands < ds.raster.bands {
                (ds.raster.data.get_f64(bands * n + i) / alpha_max(ds.raster.data_type)).clamp(0.0, 1.0)
            } else {
                1.0
            };
            values[(output_bands - 1) * n + i] = a;
            if !self.only_alpha {
                for b in 0..bands {
                    let density = if invalid_band(b) { 0.0 } else { a };
                    values[b * n + i] = if density > 0.0 { ds.raster.data.get_f64(b * n + i) * density } else { 0.0 };
                    values[(bands + b) * n + i] = density;
                }
            }
        }
        let mut out = crate::ops::derived(ds, RasterData::F64(values), output_bands)?;
        out.has_nodata = false;
        out.band_nodata = vec![None; output_bands];
        Ok(out)
    }
}
fn data_bands(ds: &RasterDataset) -> usize {
    if !ds.color_table.is_empty() {
        return 3;
    }
    ds.raster.bands - usize::from(ds.band_color_interp(ds.raster.bands).eq_ignore_ascii_case("Alpha"))
}
fn color_bands(ds: &RasterDataset) -> Result<usize> {
    let bands = data_bands(ds);
    if !matches!(bands, 1 | 3) {
        return Err(Error::Unsupported("image/alpha tiles require gray, RGB, palette, gray-alpha or RGBA input".into()));
    }
    Ok(bands)
}
fn alpha_max(dtype: DataType) -> f64 {
    match dtype {
        DataType::U16 => 65535.0,
        DataType::I16 => 32767.0,
        _ => 255.0,
    }
}
fn finish_color(ds: &RasterDataset, dtype: DataType, alpha: bool, nodata: Option<f64>) -> Result<RasterDataset> {
    let bands = (ds.raster.bands - 1) / 2;
    let n = ds.raster.cols * ds.raster.rows;
    let mut values = vec![0.0; n * (bands + usize::from(alpha))];
    for i in 0..n {
        let a = ds.raster.data.get_f64(2 * bands * n + i);
        for b in 0..bands {
            let density = ds.raster.data.get_f64((bands + b) * n + i);
            values[b * n + i] = if density > 1e-10 { ds.raster.data.get_f64(b * n + i) / density } else { nodata.unwrap_or(0.0) };
        }
        if alpha {
            values[bands * n + i] = a.clamp(0.0, 1.0) * alpha_max(dtype);
        }
    }
    let chunk_len = crate::par::chunk_len(values.len(), 1 << 16);
    crate::par::chunks_mut(&mut values, chunk_len, |_, chunk| {
        for value in chunk {
            *value = crate::ops::convert_value(*value, dtype);
        }
    });
    let data = RasterData::from_f64_vec(dtype, values);
    let mut out = crate::ops::derived(ds, data, bands + usize::from(alpha))?;
    out.has_nodata = !alpha && nodata.is_some();
    if let Some(nd) = nodata {
        out.raster.nodata = nd;
    }
    let colors: &[&str] = if bands == 1 { &["Gray", "Alpha"] } else { &["Red", "Green", "Blue", "Alpha"] };
    out.band_metadata =
        colors[..out.raster.bands].iter().map(|c| crate::BandMetadata { color_interp: Some((*c).into()), ..Default::default() }).collect();
    Ok(out)
}
fn encode_png(ds: &RasterDataset) -> Result<Vec<u8>> {
    let r = &ds.raster;
    let colors = [png::ColorType::Grayscale, png::ColorType::GrayscaleAlpha, png::ColorType::Rgb, png::ColorType::Rgba];
    let mut bytes = Vec::new();
    let err = |e: png::EncodingError| Error::InvalidData(format!("PNG tile: {e}"));
    {
        let mut encoder = png::Encoder::new(&mut bytes, r.cols as u32, r.rows as u32);
        encoder.set_color(colors[r.bands - 1]);
        encoder.set_depth(png::BitDepth::Eight);
        if r.bands == 1
            && let Some(nd) = ds.nodata()
            && (0.0..=255.0).contains(&nd)
            && nd.fract() == 0.0
        {
            encoder.set_trns((nd as u16).to_be_bytes().to_vec());
        }
        let n = r.cols * r.rows;
        let pixels: Vec<u8> = (0..n).flat_map(|i| (0..r.bands).map(move |b| r.data.get_f64(b * n + i) as u8)).collect();
        let mut writer = encoder.write_header().map_err(err)?;
        writer.write_image_data(&pixels).map_err(err)?;
        writer.finish().map_err(err)?;
    }
    Ok(bytes)
}

/// Generate to a new local directory, or fill missing tiles in an existing directory
/// with `resume`. Existing tiles are never overwritten. A failed run may leave completed
/// tiles; `resume` trusts their contents and does not verify that options match.
#[cfg(not(all(target_family = "wasm", target_os = "unknown")))]
pub fn to_directory(source: &mut dyn WarpSource, options: &TileOptions, output: &std::path::Path, resume: bool) -> Result<TileReport> {
    // Validate before creating output directories.
    let info = source.info()?;
    let (planned, _) = plan(&info.raster, options)?;
    if planned.count()? > options.max_tiles {
        return Err(invalid("the plan exceeds max_tiles"));
    }
    generate(source, options, &mut DirectorySink::new(output, resume)?)
}

pub(crate) struct DirectorySink<'a> {
    root: &'a std::path::Path,
    resume: bool,
}
impl DirectorySink<'_> {
    pub(crate) fn path(&self, name: &str) -> Result<std::path::PathBuf> {
        if name.is_empty() || std::path::Path::new(name).components().any(|c| !matches!(c, std::path::Component::Normal(_))) {
            return Err(invalid("output paths must be relative normal components"));
        }
        let path = self.root.join(name);
        // Refuse symlinked descendants even in resume mode.
        let mut current = self.root.to_path_buf();
        for component in std::path::Path::new(name).components() {
            current.push(component);
            match std::fs::symlink_metadata(&current) {
                Ok(meta) if meta.file_type().is_symlink() => return Err(invalid("symlinks are not accepted in tile output")),
                Ok(_) => {}
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
                Err(e) => return Err(e.into()),
            }
        }
        Ok(path)
    }
}
impl FolderSink for DirectorySink<'_> {
    fn get(&mut self, name: &str) -> Result<Option<Vec<u8>>> {
        let path = self.path(name)?;
        let metadata = match std::fs::metadata(&path) {
            Ok(metadata) => metadata,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(None),
            Err(error) => return Err(error.into()),
        };
        if !metadata.is_file() || metadata.len() > (RenderLimits::default().max_output_bytes + 16 * 1024 * 1024) as u64 {
            return Err(invalid("parent tile is not a bounded regular file"));
        }
        Ok(Some(std::fs::read(path)?))
    }
    fn exists(&mut self, name: &str) -> Result<bool> {
        let path = self.path(name)?;
        if path.exists() && !path.is_file() {
            return Err(invalid("an output tile path is not a file"));
        }
        Ok(self.resume && path.is_file())
    }
    fn put(&mut self, name: &str, bytes: &[u8]) -> Result<()> {
        use std::io::Write;
        let path = self.path(name)?;
        std::fs::create_dir_all(path.parent().unwrap())?;
        crate::vsi::write_local_atomic_with_replace(&path, false, |file| Ok(file.write_all(bytes)?))
    }
}
impl<'a> DirectorySink<'a> {
    pub(crate) fn new(root: &'a std::path::Path, resume: bool) -> Result<Self> {
        if root.exists() {
            if !resume {
                return Err(invalid("root directory exists; use resume to fill missing tiles"));
            }
            if std::fs::symlink_metadata(root)?.file_type().is_symlink() || !root.is_dir() {
                return Err(invalid("root must be a real directory"));
            }
        } else {
            std::fs::create_dir(root)?;
        }
        Ok(Self { root, resume })
    }
}

