//! Projections PROJ computes with ellipsoidal formulas on an ellipsoid (#126): Equidistant
//! Cylindrical (EPSG method 1028, PROJ 9.8 and later), Sinusoidal, Bonne and Gnomonic (Karney's
//! ellipsoidal gnomonic), and Miller and Van der Grinten (spherical, on the sphere of the
//! ellipsoid's area). Each is checked on WGS 84 and on a sphere, forward and inverse, against
//! pyproj (PROJ 9.8.1), from the geographic CRS on the same ellipsoid, so that no datum
//! transformation is involved.

use terrio::crs::{SpatialRef, Transformer};

const WGS84_GEOG: &str = "+proj=longlat +ellps=WGS84 +no_defs";
const SPHERE_GEOG: &str = "+proj=longlat +R=6371000 +no_defs";

/// Checks PROJ's points (longitude, latitude in degrees, x, y in metres) forward and inverse, to
/// 1 mm (or 1e-12 of the coordinate, for the gnomonic's huge ones near the horizon) and 1e-8°.
fn check(proj: &str, geog: &str, points: &[(f64, f64, f64, f64)]) {
    let crs = SpatialRef::from_proj4(proj).unwrap();
    let geog = SpatialRef::from_proj4(geog).unwrap();
    let fwd = Transformer::new(&geog, &crs).unwrap();
    let inv = Transformer::new(&crs, &geog).unwrap();
    for &(lon, lat, x, y) in points {
        let (tx, ty) = fwd.transform(lon, lat).unwrap();
        let tol = 1e-3_f64.max(1e-12 * x.hypot(y));
        assert!((tx - x).abs() < tol && (ty - y).abs() < tol, "{proj}: forward ({lon}, {lat}): ({tx}, {ty}), PROJ ({x}, {y})");
        let (tlon, tlat) = inv.transform(x, y).unwrap();
        // At a pole, any longitude.
        let dlon = if lat.abs() > 89.999 { 0.0 } else { (tlon - lon + 540.0).rem_euclid(360.0) - 180.0 };
        assert!(dlon.abs() < 1e-8 && (tlat - lat).abs() < 1e-8, "{proj}: inverse ({x}, {y}): ({tlon}, {tlat}), PROJ ({lon}, {lat})");
    }
}

/// Checks that PROJ refuses (returns infinities for) points terrio must refuse too.
fn check_hidden(proj: &str, geog: &str, points: &[(f64, f64)]) {
    let crs = SpatialRef::from_proj4(proj).unwrap();
    let geog = SpatialRef::from_proj4(geog).unwrap();
    let fwd = Transformer::new(&geog, &crs).unwrap();
    for &(lon, lat) in points {
        let r = fwd.transform(lon, lat);
        assert!(r.is_err() || !r.unwrap().0.is_finite(), "{proj}: forward of ({lon}, {lat}) beyond the horizon succeeded");
    }
}

#[test]
fn eqc_matches_proj() {
    check(EQC_WGS84_PROJ, WGS84_GEOG, EQC_WGS84);
    check(EQC_SPHERE_PROJ, SPHERE_GEOG, EQC_SPHERE);
}

#[test]
fn eqc_epsg_codes_match_proj() {
    // EPSG:4087 (method 1028) and the deprecated 32662 and 32663 (method 9823, the spherical
    // one): PROJ uses the ellipsoidal formulas for all three since they are on WGS 84.
    let wgs84 = SpatialRef::from_epsg(4326).unwrap();
    for (code, points) in [(4087, EPSG_4087), (32662, EPSG_32662), (32663, EPSG_32663)] {
        let crs = SpatialRef::from_epsg(code).unwrap();
        let fwd = Transformer::new(&wgs84, &crs).unwrap();
        let inv = Transformer::new(&crs, &wgs84).unwrap();
        for &(lon, lat, x, y) in points {
            let (tx, ty) = fwd.transform(lon, lat).unwrap();
            assert!((tx - x).abs() < 1e-3 && (ty - y).abs() < 1e-3, "EPSG:{code}: forward ({lon}, {lat}): ({tx}, {ty}), PROJ ({x}, {y})");
            let (tlon, tlat) = inv.transform(x, y).unwrap();
            assert!((tlon - lon).abs() < 1e-8 && (tlat - lat).abs() < 1e-8, "EPSG:{code}: inverse ({x}, {y}): ({tlon}, {tlat})");
        }
    }
}

