#[test]
fn gnom_refuses_points_beyond_the_horizon() {
    // Just inside the horizon of the ellipsoidal gnomonic (89.9° of arc from the centre), PROJ's
    // coordinates are huge but finite; just past it, and farther, infinite.
    check(GNOM_WGS84_PROJ, WGS84_GEOG, GNOM_EDGE_WGS84);
    check_hidden(GNOM_WGS84_PROJ, WGS84_GEOG, GNOM_HIDDEN);
    check_hidden(GNOM_WGS84_PROJ, WGS84_GEOG, GNOM_PAST_EDGE_WGS84);
    check_hidden(GNOM_SPHERE_PROJ, SPHERE_GEOG, GNOM_HIDDEN);
}

