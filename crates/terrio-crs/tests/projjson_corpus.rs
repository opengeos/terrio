//! What terrio-crs understands of every EPSG and ESRI CRS, against PROJ 9.9.0, through PROJJSON:
//! each CRS's WKT 2 (`WKT2_2019`), GDAL WKT 1 (`WKT1_GDAL`) and ESRI WKT 1 (`WKT1_ESRI`) as PROJ
//! writes them is read by `SpatialRef::from_wkt` and written back by `SpatialRef::to_projjson`, and
//! compared field by field with the PROJJSON PROJ writes for the same text (`CRS.from_wkt(text)`).
//! The fields that differ today are recorded in `data/projjson_corpus_diffs.tsv` (and
//! `projjson_corpus_diffs_fallback.tsv` with `wbprojection-fallback`), grouped by the set of
//! differing fields. The test fails on any change to them, better or worse, so that a change to
//! how WKT is read shows exactly what it changes (#1058). Record a deliberate change with
//! `TERRIO_RECORD=1`.
//!
//! Generated by `scripts/gen_projjson_corpus.py` with pyproj 3.8.0 (PROJ 9.9.0, network off).
//! Compared: what a CRS is: types; the IDs and names of CRSs; the names and values of datums,
//! ellipsoids and prime meridians; axis directions and units; method names and IDs; parameter
//! values, keyed by their ID (else their name); and the components of compound and bound CRSs.
//! Values are compared in metres, degrees and unity within a relative 1e-9, and a differing number
//! records the decade of its difference; a value given with its unit on both sides is compared
//! with the unit's kind too. Left out: usages, remarks, the names of axes and conversions, the
//! names of parameters (which key them only where they have no ID), axis abbreviations, ensemble
//! members and accuracy, and the IDs of objects other than CRSs, methods and parameters.

#[path = "support/projjson_compare.rs"]
mod projjson_compare;

use projjson_compare::{check_recorded, compare, corpus, grouped};
use serde_json::Value;
use terrio_crs::SpatialRef;

/// The recorded differences, one file with `wbprojection-fallback` (which reads more WKT) and one
/// without.
#[cfg(not(feature = "wbprojection-fallback"))]
const DIFFS: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/data/projjson_corpus_diffs.tsv");
#[cfg(feature = "wbprojection-fallback")]
const DIFFS: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/data/projjson_corpus_diffs_fallback.tsv");

/// The paths at which terrio's PROJJSON differs from PROJ's, or `!` and the error when terrio
/// writes none.
fn differences(text: &str, proj: &Value) -> String {
    let ours = match SpatialRef::from_wkt(text).to_projjson() {
        Ok(json) => match serde_json::from_str::<Value>(&json) {
            Ok(v) => v,
            Err(e) => return format!("!invalid PROJJSON: {e}"),
        },
        Err(e) => return format!("!{}", e.to_string().replace(['\t', '\n'], " ")),
    };
    compare(&ours, proj)
}

#[test]
fn every_crs_reads_as_recorded_against_proj() {
    let corpus =
        corpus(&[&include_bytes!("data/projjson_corpus_epsg.jsonl.zst")[..], &include_bytes!("data/projjson_corpus_esri.jsonl.zst")[..]]);
    check_recorded(DIFFS, &grouped(&corpus, differences));
}
