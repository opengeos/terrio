#!/usr/bin/env bash
# Renders the Homebrew tap (opengeos/homebrew-terrio) for one release: the `terrio` cask, the
# command-line binary from the release's macOS and Linux archives.
#
#   packaging/homebrew/render.sh <version> <checksums file> <tap folder>
#
# Writes <tap>/Casks/terrio.rb. The checksums file holds the lines of the release's *.sha256 files.
set -euo pipefail

usage="usage: render.sh <version> <checksums file> <tap folder>"
version="${1:?$usage}"
version="${version#v}"
sums="${2:?$usage}"
tap="${3:?$usage}"

# Only final releases: a pre-release suffix would make Homebrew treat it as the newest version.
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "not an X.Y.Z version: $version" >&2; exit 1; }

# The checksum of one target's archive, failing when the checksums file lacks it.
sha() {
  local file="terrio-cli-v$version-$1.tar.gz" h
  h="$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$sums")"
  [[ "$h" =~ ^[0-9a-f]{64}$ ]] || { echo "no checksum for $file in $sums" >&2; return 1; }
  echo "$h"
}

mac_arm="$(sha aarch64-apple-darwin)"
mac_intel="$(sha x86_64-apple-darwin)"
linux_arm="$(sha aarch64-unknown-linux-musl)"
linux_intel="$(sha x86_64-unknown-linux-musl)"

mkdir -p "$tap/Casks"

# The macOS binaries are not notarized, and Homebrew quarantines what a cask downloads: without the
# postflight, Gatekeeper would refuse to run the command.
cat > "$tap/Casks/terrio.rb" <<RUBY
# Generated by packaging/homebrew/render.sh in opengeos/terrio on every release; do not edit by hand.
cask "terrio" do
  arch arm: "aarch64", intel: "x86_64"
  os macos: "apple-darwin", linux: "unknown-linux-musl"

  version "$version"
  sha256 arm:          "$mac_arm",
         intel:        "$mac_intel",
         arm64_linux:  "$linux_arm",
         x86_64_linux: "$linux_intel"

  url "https://github.com/opengeos/terrio/releases/download/v#{version}/terrio-cli-v#{version}-#{arch}-#{os}.tar.gz"
  name "Terrio"
  desc "Geospatial raster and vector data I/O and processing"
  homepage "https://terrio.dev/"

  livecheck do
    url :url
    strategy :github_latest
  end

  binary "terrio-cli-v#{version}-#{arch}-#{os}/terrio"

  postflight_steps do
    on_macos do
      run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{staged_path}}"]
    end
  end
end
RUBY
